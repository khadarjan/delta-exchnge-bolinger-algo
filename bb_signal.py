"""
Fetches candles from Delta Exchange and reproduces the exact Band Pierce /
Band Break Exhaustion signal logic from the BBAWE Pine Script indicator.

  Band Pierce (C1/C2):
    C1 = candle whose low/high pierces the lower/upper Bollinger Band
         but CLOSES back inside it (rejection wick).
    C2 = the very next candle. If it breaks C1's high (buy) / low (sell)
         by BB_BREAK_BUFFER points -> signal. If not -> setup dropped.

  Band Break Exhaustion (C1/C2):
    C1 = candle whose ENTIRE range (O/H/L/C) sits fully outside a band
         (low > upper band -> sell exhaustion candle, high < lower band
         -> buy exhaustion candle).
    C2 = the very next candle. If it breaks C1's high (buy) / low (sell)
         by BB_BREAK_BUFFER points -> signal. If not -> setup dropped.

  Both setup types are single-shot: a setup either confirms on the very
  next candle or is dropped — there is no waiting for later candles,
  matching the Pine Script's non-repainting bar-by-bar logic.

  SL = clamped to MAX_SL_POINTS from entry.
  TP = RR x risk, floored at MIN_TARGET_POINTS.
"""
import time
import requests
import pandas as pd
import config as cfg

RES_SECONDS = {"1m": 60, "5m": 300, "15m": 900, "30m": 1800, "1h": 3600,
               "2h": 7200, "4h": 14400, "6h": 21600, "1d": 86400}


def fetch_candles(symbol: str, resolution: str, count: int, include_forming: bool = False) -> pd.DataFrame:
    """Pull the most recent `count` candles from Delta's public history endpoint."""
    end = int(time.time())
    step = RES_SECONDS[resolution]
    start = end - step * (count + 5)

    url = f"{cfg.BASE_URL}/v2/history/candles"
    params = {"symbol": symbol, "resolution": resolution, "start": start, "end": end}
    r = requests.get(url, params=params, timeout=15)
    r.raise_for_status()
    payload = r.json()
    if not payload.get("success", True) and "result" not in payload:
        raise RuntimeError(f"Candle fetch failed: {payload}")

    data = payload.get("result", [])
    if not data:
        raise RuntimeError("No candle data returned — check symbol/resolution.")

    df = pd.DataFrame(data)
    df = df.rename(columns={"time": "timestamp"})
    df = df[["timestamp", "open", "high", "low", "close", "volume"]].astype(float)
    df = df.sort_values("timestamp").reset_index(drop=True)

    # Drop the still-forming candle unless the caller (intrabar mode) wants to watch it.
    if not include_forming and df["timestamp"].iloc[-1] + step > time.time():
        df = df.iloc[:-1].reset_index(drop=True)
    return df


def compute_bands(df: pd.DataFrame) -> pd.DataFrame:
    """Adds basis/upper/lower Bollinger Band columns, mirroring the Pine calc."""
    df = df.copy()
    if cfg.BB_USE_EMA:
        basis = df["close"].ewm(span=cfg.BB_LENGTH, adjust=False).mean()
    else:
        basis = df["close"].rolling(cfg.BB_LENGTH).mean()
    # ddof=0 -> population stdev, matching Pine's ta.stdev()
    dev = df["close"].rolling(cfg.BB_LENGTH).std(ddof=0) * cfg.BB_MULT

    df["bb_basis"] = basis
    df["bb_upper"] = basis + dev
    df["bb_lower"] = basis - dev
    return df


def compute_signal(df: pd.DataFrame) -> dict:
    """
    Runs the full Band-Pierce and Band-Break-Exhaustion C1/C2 state machines
    over the candle series and returns the signal (if any) generated by the
    LAST FULLY CLOSED candle acting as C2 for either setup type.

    Returns a dict:
      {"signal": "BUY"/"SELL"/None, "setup_type": "pierce"/"band_break"/None,
       "entry", "sl", "tp", "c1_index", "bar_index"}
    """
    df = compute_bands(df)

    # Independent armed states — pierce and band-break setups can't both
    # fire off the same candle (their C1 conditions are mutually exclusive),
    # but we keep them separate for clarity and independent buffers/tuning.
    pierce_buy_armed = pierce_sell_armed = False
    bb_buy_armed = bb_sell_armed = False
    pierce_c1_high = pierce_c1_low = None
    bb_c1_high = bb_c1_low = None
    breakout_pierce_long = breakout_pierce_short = None
    breakout_bb_long = breakout_bb_short = None
    pierce_c1_index = bb_c1_index = None

    result = {"signal": None, "setup_type": None, "entry": None, "sl": None,
              "tp": None, "c1_index": None, "bar_index": None}

    start_idx = cfg.BB_LENGTH
    prev_row = None

    for i in range(start_idx, len(df)):
        row = df.iloc[i]
        high, low, close = row.high, row.low, row.close
        upper, lower = row.bb_upper, row.bb_lower

        # ── Step 1: this candle acts as C2 → check buffered breakouts ──
        pierce_buy_signal   = pierce_buy_armed  and high > breakout_pierce_long
        pierce_sell_signal  = pierce_sell_armed and low  < breakout_pierce_short
        bb_buy_signal        = bb_buy_armed      and high > breakout_bb_long
        bb_sell_signal       = bb_sell_armed     and low  < breakout_bb_short

        if pierce_buy_signal:
            entry = breakout_pierce_long
            risk = min(entry - pierce_c1_low, cfg.MAX_SL_POINTS)
            sl = entry - risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            result = {"signal": "BUY", "setup_type": "pierce", "entry": entry,
                      "sl": sl, "tp": entry + tgt, "c1_index": pierce_c1_index,
                      "bar_index": i}

        if pierce_sell_signal:
            entry = breakout_pierce_short
            risk = min(pierce_c1_high - entry, cfg.MAX_SL_POINTS)
            sl = entry + risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            result = {"signal": "SELL", "setup_type": "pierce", "entry": entry,
                      "sl": sl, "tp": entry - tgt, "c1_index": pierce_c1_index,
                      "bar_index": i}

        if bb_buy_signal:
            entry = breakout_bb_long
            risk = min(entry - bb_c1_low, cfg.MAX_SL_POINTS)
            sl = entry - risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            result = {"signal": "BUY", "setup_type": "band_break", "entry": entry,
                      "sl": sl, "tp": entry + tgt, "c1_index": bb_c1_index,
                      "bar_index": i}

        if bb_sell_signal:
            entry = breakout_bb_short
            risk = min(bb_c1_high - entry, cfg.MAX_SL_POINTS)
            sl = entry + risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            result = {"signal": "SELL", "setup_type": "band_break", "entry": entry,
                      "sl": sl, "tp": entry - tgt, "c1_index": bb_c1_index,
                      "bar_index": i}

        # setups consumed either way (pass or fail) — single-shot, no re-arming
        pierce_buy_armed = pierce_sell_armed = False
        bb_buy_armed = bb_sell_armed = False

        # ── Step 2: does THIS candle qualify as a new C1? ──
        # Band Pierce: wick breaches the band but close comes back inside it.
        pierce_low_ok  = low  <= lower and close > lower
        pierce_high_ok = high >= upper and close < upper

        if pierce_low_ok:
            pierce_c1_high, pierce_c1_low = high, low
            breakout_pierce_long = high + cfg.BB_BREAK_BUFFER
            pierce_buy_armed = True
            pierce_c1_index = i

        if pierce_high_ok:
            pierce_c1_high, pierce_c1_low = high, low
            breakout_pierce_short = low - cfg.BB_BREAK_BUFFER
            pierce_sell_armed = True
            pierce_c1_index = i

        # Band Break Exhaustion: the ENTIRE candle sits outside the band.
        band_break_up_ok   = low  > upper   # fully above -> sell exhaustion candle
        band_break_down_ok = high < lower   # fully below -> buy exhaustion candle

        if band_break_down_ok:
            bb_c1_high, bb_c1_low = high, low
            breakout_bb_long = high + cfg.BB_BREAK_BUFFER
            bb_buy_armed = True
            bb_c1_index = i

        if band_break_up_ok:
            bb_c1_high, bb_c1_low = high, low
            breakout_bb_short = low - cfg.BB_BREAK_BUFFER
            bb_sell_armed = True
            bb_c1_index = i

        prev_row = row

    return result

def armed_setups(df: pd.DataFrame) -> list:
    """
    Setups ARMED by the last row of `df` (pass CLOSED candles only): the C1 candidates whose
    buffered breakout level C2 (the next candle) can still trigger. Same C1 conditions, buffer,
    SL clamp and TP floor as compute_signal(), so the two modes trade the same setups.
    Each item: {"signal","setup_type","entry"(trigger level),"sl","tp","c1_index"}.
    """
    d = compute_bands(df)
    if len(d) <= cfg.BB_LENGTH:
        return []
    row = d.iloc[-1]
    if pd.isna(row.bb_upper) or pd.isna(row.bb_lower):
        return []
    high, low, close = float(row.high), float(row.low), float(row.close)
    upper, lower = float(row.bb_upper), float(row.bb_lower)
    buf = cfg.BB_BREAK_BUFFER
    out = []

    def mk(signal, setup_type, trigger):
        if signal == "BUY":
            risk = min(trigger - low, cfg.MAX_SL_POINTS)
            sl, tp = trigger - risk, trigger + max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
        else:
            risk = min(high - trigger, cfg.MAX_SL_POINTS)
            sl, tp = trigger + risk, trigger - max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
        out.append({"signal": signal, "setup_type": setup_type, "entry": float(trigger),
                    "sl": float(sl), "tp": float(tp), "c1_index": len(d) - 1})

    if low <= lower and close > lower:  mk("BUY",  "pierce",     high + buf)   # band pierce, bullish rejection
    if high >= upper and close < upper: mk("SELL", "pierce",     low - buf)    # band pierce, bearish rejection
    if high < lower:                    mk("BUY",  "band_break", high + buf)   # whole candle below lower band
    if low > upper:                     mk("SELL", "band_break", low - buf)    # whole candle above upper band
    return out