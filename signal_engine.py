"""
Fetches 4H candles from Delta Exchange and reproduces the exact C1/C2 signal
logic from the Pine Script indicator:

  C1 = candle that TOUCHES the EMA50 (wick pierces it) and CLOSES on the
       trend side (green & above EMA for bulls, red & below EMA for bears),
       with total wick <= MAX_WICK_PCT of its range.
  C2 = the very next candle. If it breaks C1's high/low + buffer -> signal.
       If it doesn't -> setup is dropped (no waiting for later candles).
  SL = clamped to MAX_SL_POINTS from entry.
  TP = RR x risk, floored at MIN_TARGET_POINTS.
"""
import time
import requests
import pandas as pd
import config as cfg


def fetch_candles(symbol: str, resolution: str, count: int) -> pd.DataFrame:
    """Pull the most recent `count` candles from Delta's public history endpoint."""
    end = int(time.time())
    # rough seconds-per-candle map to size the start window generously
    seconds_map = {"1m": 60, "5m": 300, "15m": 900, "1h": 3600, "4h": 14400, "1d": 86400}
    step = seconds_map.get(resolution, 14400)
    start = end - step * (count + 5)

    url = f"{cfg.BASE_URL}/v2/history/candles"
    params = {"symbol": symbol, "resolution": resolution, "start": start, "end": end}
    r = requests.get(url, params=params, timeout=15)
    r.raise_for_status()
    payload = r.json()
    if not payload.get("success", True) and "result" not in payload:
        raise RuntimeError(f"Candle fetch failed: {payload}")

    data = payload.get("result", [])
    if not data:
        raise RuntimeError("No candle data returned — check symbol/resolution.")

    df = pd.DataFrame(data)
    # Delta returns time in unix seconds, oldest-first or newest-first depending on version —
    # normalize by sorting explicitly.
    df = df.rename(columns={"time": "timestamp"})
    df = df[["timestamp", "open", "high", "low", "close", "volume"]].astype(float)
    df = df.sort_values("timestamp").reset_index(drop=True)
    return df


def compute_signal(df: pd.DataFrame) -> dict:
    """
    Runs the full C1/C2 state machine over the candle series and returns
    the signal (if any) generated by the LAST FULLY CLOSED candle acting as C2.

    Returns a dict: {"signal": "BUY"/"SELL"/None, "entry", "sl", "tp", "c1_index"}
    """
    df = df.copy()
    df["ema50"] = df["close"].ewm(span=cfg.EMA_LEN, adjust=False).mean()

    long_armed = False
    short_armed = False
    c1_high = c1_low = None
    breakout_long = breakout_short = None
    c1_index = None

    result = {"signal": None, "entry": None, "sl": None, "tp": None, "c1_index": None}

    # We need EMA warmed up — skip the first EMA_LEN candles from consideration
    start_idx = cfg.EMA_LEN

    for i in range(start_idx, len(df)):
        row = df.iloc[i]
        high, low, close, open_ = row.high, row.low, row.close, row.open
        ema = row.ema50

        # ── Step 1: this candle acts as C2 → check buffered breakout ──
        buy_signal = long_armed and high > breakout_long
        sell_signal = short_armed and low < breakout_short

        if buy_signal:
            entry = breakout_long
            risk = min(entry - c1_low, cfg.MAX_SL_POINTS)
            sl = entry - risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            tp = entry + tgt
            result = {"signal": "BUY", "entry": entry, "sl": sl, "tp": tp,
                       "c1_index": c1_index, "bar_index": i}

        if sell_signal:
            entry = breakout_short
            risk = min(c1_high - entry, cfg.MAX_SL_POINTS)
            sl = entry + risk
            tgt = max(cfg.RR * risk, cfg.MIN_TARGET_POINTS)
            tp = entry - tgt
            result = {"signal": "SELL", "entry": entry, "sl": sl, "tp": tp,
                       "c1_index": c1_index, "bar_index": i}

        # setup consumed either way (pass or fail)
        long_armed = False
        short_armed = False

        # ── Step 2: does THIS candle qualify as a new C1? ──
        candle_range = high - low
        body = abs(close - open_)
        wick_pct = 0.0 if candle_range == 0 else (candle_range - body) / candle_range * 100

        is_green = close > open_
        is_red = close < open_
        touched_from_below = low <= ema
        touched_from_above = high >= ema

        bull_c1_ok = (close > ema) and touched_from_below and is_green and (wick_pct <= cfg.MAX_WICK_PCT)
        bear_c1_ok = (close < ema) and touched_from_above and is_red and (wick_pct <= cfg.MAX_WICK_PCT)

        if bull_c1_ok:
            c1_high, c1_low = high, low
            breakout_long = high + cfg.BUFFER_POINTS
            long_armed = True
            c1_index = i

        if bear_c1_ok:
            c1_high, c1_low = high, low
            breakout_short = low - cfg.BUFFER_POINTS
            short_armed = True
            c1_index = i

    return result
